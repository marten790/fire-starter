import type { FiringSession, HeatingLogEntry } from '../types/firing'

function entry(
  elapsedHours: number,
  clockTime: string,
  dial: number,
  tempC: number,
  extras: Partial<HeatingLogEntry> = {},
): HeatingLogEntry {
  const elapsedSeconds = Math.round(elapsedHours * 3600)
  return {
    id: `e-${elapsedHours}-${clockTime}-${tempC}`,
    elapsedMinutes: Math.floor(elapsedSeconds / 60),
    elapsedSeconds,
    clockTime,
    dial,
    tempC,
    ...extras,
  }
}

function at(year: number, monthIndex: number, day: number, hour = 8, minute = 0) {
  return new Date(year, monthIndex, day, hour, minute, 0, 0).getTime()
}

